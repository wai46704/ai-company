// セッション開始時に「申し送り.md」の未回答セクションを表示するフック用スクリプト
// 目的: 前セッションで社長が答えた質問を、新セッションで再質問しないようにする。
//       セッションを始めた瞬間に「社長への未回答の質問」を毎回自動で目に入れる。
// 挙動: 申し送り.md の「## 🔴 未回答」セクションだけを抜き出して表示する。
//       ファイルが無い・未回答が空のときは何も出さない（余計なノイズを出さない）。
const fs = require("fs");

// 申し送り台帳の絶対パス（作業ディレクトリがどこでも読めるように絶対指定）
const LEDGER = "C:/Users/naoki/Documents/ai-company/編集部/申し送り.md";

try {
  const text = fs.readFileSync(LEDGER, "utf8");
  // 「## 🔴 未回答」から次の「## 🟢」の直前までを取り出す
  const matched = text.match(/## 🔴 未回答[\s\S]*?(?=\n## 🟢)/);
  if (matched && matched[0].trim()) {
    process.stdout.write(
      "📋【申し送り｜前セッションからの持ち越し】\n" +
      "回答済みの質問は聞き直さないこと。全体は 編集部/申し送り.md を参照。\n\n" +
      matched[0].trim() + "\n"
    );
  }
} catch (e) {
  // 台帳がまだ無い場合などは沈黙（フックがセッション開始を邪魔しないように）
}
